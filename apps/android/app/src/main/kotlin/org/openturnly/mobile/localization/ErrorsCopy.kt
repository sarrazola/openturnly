    private val table get() = if (AppLocale.isSpanish) es else en

    /** `<field>_<code>`, then the code alone. */
    fun describeField(field: String, code: String): String? {
        val leaf = field.substringAfterLast('.')
        return table["${leaf}_$code"] ?: table[code]
    }

    /** A field error first (it says more than "validation_failed"), then the code, then a generic line. */
    fun describe(code: String, fields: Map<String, String>): String {
        if (code == "validation_failed" || code == "customer_exists") {
            fields.entries.firstNotNullOfOrNull { (field, value) -> describeField(field, value) }?.let { return it }
        }
        return table[code] ?: generic
    }
